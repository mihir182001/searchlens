"""
loading + label-encoding for the query
intent classification dataset generated by generate_query_intent_data.py.

Deliberately has NO dependency on torch/transformers -- this is pure Python
+ csv, so it's fully unit-testable in the sandbox (no HF weights needed).
src/models/query_intent_classifier.py wraps this with the actual
DistilBERT tokenizer/model on your machine.
"""
import csv
from pathlib import Path

RAW_DIR = Path(__file__).resolve().parents[2] / "data" / "raw"

# Fixed, sorted order this is the canonical int<->label mapping used
# everywhere (training, inference, routing). Sorted alphabetically so it's
# deterministic without needing to persist a separate mapping file.
INTENT_LABELS = ["comparison", "exploratory", "factual", "how-to", "navigational"]


class LabelEncoder:
    """Tiny str<->int encoder over a fixed label set (INTENT_LABELS), not
    fit from data -- so it can't silently produce a different mapping if a
    class happens to be missing from one split.
    """

    def __init__(self, labels: list = None):
        self.labels = list(labels) if labels is not None else list(INTENT_LABELS)
        self._label_to_id = {label: i for i, label in enumerate(self.labels)}

    def encode(self, label: str) -> int:
        if label not in self._label_to_id:
            raise ValueError(f"Unknown intent label {label!r}. Known labels: {self.labels}")
        return self._label_to_id[label]

    def decode(self, label_id: int) -> str:
        if not (0 <= label_id < len(self.labels)):
            raise ValueError(f"label_id {label_id} out of range for {len(self.labels)} labels")
        return self.labels[label_id]

    @property
    def num_labels(self) -> int:
        return len(self.labels)


def load_intent_csv(path: Path) -> list:
    """Returns a list of (query, intent) tuples from a CSV written by
    generate_query_intent_data.py. Raises FileNotFoundError with a helpful
    message (matching the pattern in src/data/loader.py) if it's missing.
    """
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(
            f"{path} not found. Run `python -m src.data.generate_query_intent_data` first."
        )
    rows = []
    with open(path, encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            rows.append((row["query"], row["intent"]))
    return rows


def load_intent_train() -> list:
    return load_intent_csv(RAW_DIR / "query_intent_train.csv")


def load_intent_val() -> list:
    return load_intent_csv(RAW_DIR / "query_intent_val.csv")


def encode_rows(rows: list, encoder: LabelEncoder = None):
    """rows: list of (query, intent) tuples -> (queries, label_ids) as two
    parallel lists, ready to hand to a tokenizer/torch Dataset.
    """
    encoder = encoder or LabelEncoder()
    queries = [q for q, _ in rows]
    label_ids = [encoder.encode(intent) for _, intent in rows]
    return queries, label_ids